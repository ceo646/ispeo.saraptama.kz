def km(a, b):
    dy = (a[0] - b[0]) * 111.2
    dx = (a[1] - b[1]) * 111.2 * math.cos(math.radians(52.28))
    return math.hypot(dx, dy)


def zone_of(lat, lon, address=None):
    if address and PROM.search(address):
        return "Промзоны (Северная, Центральная, Восточная)", 0.0
    best, bz = 1e9, None
    for z, pts in ZONES.items():
        for p in pts:
            d = km((lat, lon), p)
            if d < best:
                best, bz = d, z
    return bz, best
